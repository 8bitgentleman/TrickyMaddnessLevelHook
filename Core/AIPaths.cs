        // One AI route before it becomes an AIPath3D. A NaN Y means the source was
        // 2D (sidecar / maker points are world XZ only) and BuildAIPathNetwork has
        // to find the ground under it.
        internal sealed class RouteDraft
        {
            public string Name;
            public bool Spine;   // the race line: the complete, finish-reaching backstop
            public readonly List<Vector3> Points = new List<Vector3>();
            public readonly List<bool> Windups = new List<bool>();
            // "rail <SplineName>" in the sidecar: this fragment ends in front of that
            // grind rail and gets the game's own Rail connection (AI_ROUTE_CHARTING_PLAN.md
            // § Rail lanes). Null for every other route.
            public string RailName;
        }

        // Reads routes from "<map>.aipaths.txt" next to the .asset (generated by
        // gen_aipaths.py from the bundle's own data). Plain text, NOT JsonUtility —
        // that is the same serializer that loses the nested class in the first
        // place. Format: '#' comments; a line "path" starts a new path; point lines
        // are "x z windup" (two invariant-culture floats, world XZ, then 0/1).
        private static List<RouteDraft> SidecarRoutes()
        {
            var result = new List<RouteDraft>();
            if (string.IsNullOrEmpty(LoadedAssetBundle)) return result;
            string sidecarPath = Path.ChangeExtension(LoadedAssetBundle, ".aipaths.txt");
            if (!File.Exists(sidecarPath)) return result;
            try
            {
                var paths = new List<RouteDraft>();
                RouteDraft cur = null;
                int malformed = 0;
                foreach (var raw in File.ReadAllLines(sidecarPath))
                {
                    string line = raw.Trim();
                    if (line.Length == 0 || line.StartsWith("#")) continue;
                    // Header lines. Each is read on its own at load time; here they
                    // are simply not points. ⚠️ This list must cover EVERY header
                    // gen_aipaths.py can emit. A 2-token header that slips through
                    // (gravity, spawnsnap) only inflates the malformed counter, but
                    // "group SSX (2012)" is 3 tokens and would reach float.Parse.
                    if (IsHeaderLine(line)) continue;
                    if (line == "path")
                    {
                        cur = new RouteDraft();
                        paths.Add(cur);
                        continue;
                    }
                    var t = line.Split(new[] { ' ', '\t' }, StringSplitOptions.RemoveEmptyEntries);
                    // Per-path, so NOT in SidecarHeaders (those are file-level). An
                    // older Hook counts this 2-token line as malformed and drops it;
                    // the fragment then dead-ends, and TryAcquirePath's containment
                    // scan hands the COM back to the race line.
                    if (t.Length == 2 && t[0] == "rail")
                    {
                        if (cur == null) { malformed++; continue; }
                        cur.RailName = t[1];
                        continue;
                    }
                    if (t.Length < 3) { malformed++; continue; }
                    if (cur == null)
                    {
                        cur = new RouteDraft();
                        paths.Add(cur);
                    }
                    cur.Points.Add(new Vector3(
                        float.Parse(t[0], CultureInfo.InvariantCulture),
                        float.NaN,
                        float.Parse(t[1], CultureInfo.InvariantCulture)));
                    cur.Windups.Add(t[2] == "1");
                }

                int points = 0, tooShort = 0;
                foreach (var d in paths)
                {
                    if (d.Points.Count < 2) { tooShort++; continue; } // a path needs a direction
                    d.Name = "AIPath3D (sidecar " + result.Count.ToString(CultureInfo.InvariantCulture) + ")";
                    result.Add(d);
                    points += d.Points.Count;
                }
                Log.LogInfo($"[AIPaths] read {result.Count} path(s) ({points} points) from sidecar {Path.GetFileName(sidecarPath)}");
                // Both counters used to be invisible: the summary above reported only the
                // survivors, so a truncated sidecar looked exactly like a short one. A
                // path dropped here is a path the AI cannot run.
                if (malformed > 0)
                    Log.LogWarning($"[AIPaths] sidecar {Path.GetFileName(sidecarPath)}: {malformed} point line(s) "
                        + "had fewer than 3 tokens and were dropped (expected 'x z windup').");
                if (tooShort > 0)
                    Log.LogWarning($"[AIPaths] sidecar {Path.GetFileName(sidecarPath)}: {tooShort} path(s) "
                        + "had fewer than 2 points and were discarded entirely.");
                return result;
            }
            catch (Exception e)
            {
                Log.LogError($"[AIPaths] sidecar {sidecarPath} failed to load: {e}");
                return new List<RouteDraft>();
            }
        }

        // Route volume sizes, in 1x world units (multiplied by WorldScale). TM's own
        // four courses (build 25617730) measure a median half-width of 14-26 and a
        // max of 55-122, heightBelow/heightAbove 10 almost everywhere (≤30).
        // Ours are deliberately wider and taller: a rider outside EVERY volume for
        // 1.5 s respawns (AISnowboarder.GetSteeringInput), SSX fragments were never
        // authored as volumes, and converted courses carry bigger airs. The spine
        // (race line) has to cover the whole run, so it is the widest.
        const float SpineHalfWidth = 80f, BranchHalfWidth = 30f;

        const float RouteHeightBelow = 15f, RouteHeightAbove = 60f;

        // Brace (windup) points. No converted course carries any: SSX has no such
        // flag, so every sidecar point is 0 and the race line is built false. TM's
        // own four courses flag 12-19% of their knots, one knot per span, ~50 m
        // (1x) of flattish run-up ending where the path drops away (measured from
        // their exported AIPath3D profiles). For the AI a windup span is NOT a
        // charged jump — AISnowboarder.GetJumpInput is hard false — it is a
        // crouch plus a pre-loaded spin/flip carried into Takeoff, i.e. trick
        // points and so boost. KnotProfile.windup is a step function (knot i
        // holds until knot i+1), so with our dense knots every knot in the
        // run-up is flagged.
        //
        // Lip test, per knot k: the ground LipLookAhead ahead sits at least
        // LipDrop below where the approach grade (over LipBackOff behind) would
        // put it, or there is no ground under it at all (a gap). The three
        // thresholds are judgment, not measured against TM's courses.
        const float BraceSpan = 50f, LipLookAhead = 10f, LipBackOff = 20f, LipDrop = 4f;

        private static int MarkBracePoints(List<Vector3> pts, List<bool> windups, float s)
        {
            int n = pts.Count;
            if (aiBracePoints != null && !aiBracePoints.Value) return 0;
            if (n < 3 || windups.Count != n) return 0;
            for (int k = 0; k < n; k++) if (windups[k]) return 0; // authored: take as is
            var cum = new float[n];
            var gy = new float[n];
            for (int k = 0; k < n; k++)
            {
                if (k > 0)
                {
                    float dx = pts[k].x - pts[k - 1].x, dz = pts[k].z - pts[k - 1].z;
                    cum[k] = cum[k - 1] + Mathf.Sqrt(dx * dx + dz * dz);
                }
                var from = new Vector3(pts[k].x, pts[k].y + 50f * s, pts[k].z);
                gy[k] = Physics.Raycast(from, Vector3.down, out var hit, 400f * s, SpawnGroundMask, QueryTriggerInteraction.Ignore)
                    ? hit.point.y : float.NaN;
            }
            float back = LipBackOff * s, ahead = LipLookAhead * s, span = BraceSpan * s, drop = LipDrop * s;
            float lastLip = float.NegativeInfinity;
            int lips = 0, b = 0, a = 0;
            for (int k = 1; k < n; k++)
            {
                if (float.IsNaN(gy[k])) continue;
                while (b + 1 < k && cum[k] - cum[b + 1] >= back) b++;
                if (cum[k] - cum[b] < back || float.IsNaN(gy[b])) continue;
                if (a <= k) a = k + 1;
                while (a < n && cum[a] - cum[k] < ahead) a++;
                if (a >= n) break;
                if (cum[k] - lastLip < span) continue;
                float grade = (gy[k] - gy[b]) / (cum[k] - cum[b]);
                float predicted = gy[k] + grade * (cum[a] - cum[k]);
                if (!float.IsNaN(gy[a]) && predicted - gy[a] < drop) continue;
                for (int i = k - 1; i >= 0 && cum[k] - cum[i] <= span && cum[i] > lastLip; i--)
                    windups[i] = true;
                lastLip = cum[k];
                lips++;
            }
            return lips;
        }

        // AIPath3D's bake builds a NativeSpline (up-vector + length caches) that
        // costs ~1 ms per knot under Mono — 2.8 s for SSX 3 R&B's 2923 knots, paid
        // on every load and restart. AIPath3D re-samples between knots every
        // sampleSpacing anyway, so a knot that sits on the line between its
        // neighbours adds nothing. Douglas-Peucker in 3D (keeps jump lips), never
        // across a windup on/off boundary. 1x units, so it scales with the map.
        const float RouteTrimTolerance = 1f;

        // Rewrites d.Points/d.Windups (with grounded `placed` as the new points).
        private static void TrimRoute(List<Vector3> placed, RouteDraft d, float tol)
        {
            int n = placed.Count;
            if (n < 3 || d.Windups.Count != n || tol <= 0f) { d.Points.Clear(); d.Points.AddRange(placed); return; }
            var keep = new bool[n];
            keep[0] = keep[n - 1] = true;
            for (int k = 1; k < n; k++)
                if (d.Windups[k] != d.Windups[k - 1]) { keep[k] = true; keep[k - 1] = true; }
            float tol2 = tol * tol;
            var stack = new Stack<KeyValuePair<int, int>>();
            int a0 = 0;
            for (int k = 1; k < n; k++)
                if (keep[k]) { if (k - a0 > 1) stack.Push(new KeyValuePair<int, int>(a0, k)); a0 = k; }
            while (stack.Count > 0)
            {
                var span = stack.Pop();
                Vector3 a = placed[span.Key], ab = placed[span.Value] - a;
                float len2 = ab.sqrMagnitude;
                int worst = -1; float worstD = tol2;
                for (int k = span.Key + 1; k < span.Value; k++)
                {
                    Vector3 ap = placed[k] - a;
                    float t = len2 > 1e-6f ? Mathf.Clamp01(Vector3.Dot(ap, ab) / len2) : 0f;
                    float d2 = (ap - ab * t).sqrMagnitude;
                    if (d2 > worstD) { worstD = d2; worst = k; }
                }
                if (worst < 0) continue;
                keep[worst] = true;
                if (worst - span.Key > 1) stack.Push(new KeyValuePair<int, int>(span.Key, worst));
                if (span.Value - worst > 1) stack.Push(new KeyValuePair<int, int>(worst, span.Value));
            }
            var w = new List<bool>(d.Windups);
            d.Points.Clear(); d.Windups.Clear();
            for (int k = 0; k < n; k++)
                if (keep[k]) { d.Points.Add(placed[k]); d.Windups.Add(w[k]); }
        }

        // Turns the drafts into AIPath3D children of `root` under one
        // AIPathNetwork. AIPath3D bakes its samples lazily from the SplineContainer
        // (world space via the transform, so an identity root = world knots), and
        // pads m_knotProfiles to the knot count itself; we only fill the widths.
        private static AIPathNetwork BuildAIPathNetwork(GameObject root, List<RouteDraft> routes, RouteDraft raceLine)
        {
            float s = RouteScale;
            int grounded = 0, seeded = 0, blind = 0, knots = 0, built = 0, trimmed = 0;
            int braceLips = 0, braceRoutes = 0;
            var sw = System.Diagnostics.Stopwatch.StartNew();
            long tSplit, tGround = 0, tSpline = 0, tAdd = 0, tProfile = 0, tDirty = 0, tWire, tSync;
            // Only the sidecar pool (race line + SSX fragments) gets wired; maker
            // paths from the bundle are taken as authored.
            var links = routes.Contains(raceLine) ? SplitAndLink(routes, raceLine, s) : new List<KeyValuePair<int, int>>();
            tSplit = sw.ElapsedTicks;
            var made = new AIPath3D[routes.Count];
            for (int ri = 0; ri < routes.Count; ri++)
            {
                var d = routes[ri];
                try
                {
                    long t0 = sw.ElapsedTicks;
                    var go = new GameObject(d.Name);
                    // Built inactive: AIPath3D.OnEnable bakes unconditionally at its
                    // default 1-unit spacing, and our spacing/profile changes after it
                    // force a second lazy bake on first query (~6 s on SSX 3 R&B).
                    // Activating once everything is set bakes once, at our spacing.
                    go.SetActive(false);
                    go.transform.SetParent(root.transform, false);
                    // Container first and filled BEFORE AIPath3D exists, so its
                    // OnEnable bakes once instead of re-syncing on every knot.
                    var container = go.AddComponent<UnityEngine.Splines.SplineContainer>();
                    var spline = container.Spline;
                    float prevY = float.NaN;
                    int raw = d.Points.Count;
                    var placed = new List<Vector3>(d.Points.Count);
                    for (int k = 0; k < d.Points.Count; k++)
                    {
                        Vector3 p = d.Points[k];
                        if (float.IsNaN(p.y))
                        {
                            long tg = sw.ElapsedTicks;
                            p.y = GroundUnderRoute(p, raceLine, prevY, s, ref grounded, ref seeded, ref blind);
                            tGround += sw.ElapsedTicks - tg;
                        }
                        prevY = p.y;
                        placed.Add(p);
                    }
                    int lips = MarkBracePoints(placed, d.Windups, s);
                    if (lips > 0) { braceLips += lips; braceRoutes++; }
                    TrimRoute(placed, d, RouteTrimTolerance * s);
                    trimmed += raw - d.Points.Count;
                    foreach (var p in d.Points)
                        // Linear: the old AIPath was a polyline, and auto-smoothing
                        // dense SSX points overshoots at sharp fragment corners.
                        spline.Add(new Unity.Mathematics.float3(p.x, p.y, p.z), UnityEngine.Splines.TangentMode.Linear);
                    long t1 = sw.ElapsedTicks;
                    tSpline += t1 - t0;
                    var path = go.AddComponent<AIPath3D>();
                    long t2 = sw.ElapsedTicks;
                    tAdd += t2 - t1;
                    if (fSampleSpacing != null)
                        fSampleSpacing.SetValue(path, Mathf.Max(1f, 2f * s));
                    if (path.m_knotProfiles == null) path.m_knotProfiles = new List<AIPath3D.KnotProfile>();
                    while (path.m_knotProfiles.Count < d.Points.Count)
                        path.m_knotProfiles.Add(new AIPath3D.KnotProfile());
                    float half = (d.Spine ? SpineHalfWidth : BranchHalfWidth) * s;
                    for (int k = 0; k < d.Points.Count; k++)
                    {
                        var kp = path.m_knotProfiles[k];
                        kp.leftWidth = half;
                        kp.rightWidth = half;
                        kp.heightBelow = RouteHeightBelow * s;
                        kp.heightAbove = RouteHeightAbove * s;
                        kp.windup = d.Windups[k];
                    }
                    long t3 = sw.ElapsedTicks;
                    tProfile += t3 - t2;
                    go.SetActive(true);
                    tDirty += sw.ElapsedTicks - t3;
                    made[ri] = path;
                    knots += d.Points.Count;
                    built++;
                }
                catch (Exception e)
                {
                    Log.LogError($"[AIPaths] building '{d.Name}' failed: {e}");
                }
            }
            long tw = sw.ElapsedTicks;
            int wired = 0;
            foreach (var link in links)
            {
                int from = link.Key, to = link.Value;
                if (made[from] == null || made[to] == null) continue;
                if (made[from].m_connections == null) made[from].m_connections = new List<AIPath3D.PathConnection>();
                made[from].m_connections.Add(new AIPath3D.PathConnection
                {
                    type = AIPath3D.ConnectionType.Path,
                    path = made[to],
                    selectionWeight = 1f,
                    enabled = true,
                });
                wired++;
            }
            int railLinks = 0, railMissing = 0;
            for (int ri = 0; ri < routes.Count; ri++)
            {
                string want = routes[ri].RailName;
                if (string.IsNullOrEmpty(want) || made[ri] == null) continue;
                var rail = FindRailByName(want);
                if (rail == null)
                {
                    railMissing++;
                    Log.LogWarning($"[AIPaths] '{routes[ri].Name}' names rail '{want}', which this level does not have — left a plain fragment.");
                    continue;
                }
                if (made[ri].m_connections == null) made[ri].m_connections = new List<AIPath3D.PathConnection>();
                // The approach's ONLY connection (SplitAndLink gives a rail route no
                // merge link), so its weight is moot. After the grind the rider is
                // past the approach's end and TryAcquirePath's all-paths scan picks
                // up the race-line piece it is inside — the charting tool only names
                // rails that lie wholly within the spine volume.
                made[ri].m_connections.Add(new AIPath3D.PathConnection
                {
                    type = AIPath3D.ConnectionType.Rail,
                    rail = rail,
                    selectionWeight = 1f,
                    enabled = true,
                });
                railLinks++;
            }
            if (railLinks > 0 || railMissing > 0)
                Log.LogInfo($"[AIPaths] {railLinks} rail connection(s), {railMissing} unknown rail name(s)");
            int deadEnds = 0;
            foreach (var p in made)
                if (p != null && (p.m_connections == null || p.m_connections.Count == 0)) deadEnds++;
            if (links.Count > 0)
                Log.LogInfo($"[AIPaths] wired {wired} connection(s); {deadEnds} route(s) end with none (the finish, or a fragment that merges nowhere)");
            tWire = sw.ElapsedTicks - tw;
            long ts = sw.ElapsedTicks;
            var network = root.AddComponent<AIPathNetwork>();
            network.SyncPaths();
            tSync = sw.ElapsedTicks - ts;
            double ms = 1000.0 / System.Diagnostics.Stopwatch.Frequency;
            Log.LogInfo($"[LoadTime] BuildAIPathNetwork breakdown: SplitAndLink {tSplit * ms:0} ms, spline fill {tSpline * ms:0} ms "
                + $"(of which GroundUnderRoute {tGround * ms:0} ms), AddComponent<AIPath3D> {tAdd * ms:0} ms, knot profiles {tProfile * ms:0} ms, "
                + $"activate (bake) {tDirty * ms:0} ms, wiring {tWire * ms:0} ms, AIPathNetwork add+SyncPaths {tSync * ms:0} ms, total {sw.ElapsedTicks * ms:0} ms");
            Log.LogInfo($"[AIPaths] AIPathNetwork: {built} AIPath3D route(s), {knots} knot(s) at scale {s:0.###}; "
                + $"2D points grounded by raycast {grounded}, from race-line/previous height {seeded}, unresolved {blind}");
            Log.LogInfo($"[AIPaths] trimmed {trimmed} near-collinear knot(s) (tolerance {RouteTrimTolerance * s:0.##}) — AIPath3D's spline setup costs ~1 ms per knot");
            Log.LogInfo($"[AIPaths] brace points: {braceLips} lip(s) on {braceRoutes} route(s) got a {BraceSpan * s:0} unit windup run-up");
            if (blind > 0)
                Log.LogWarning($"[AIPaths] {blind} route point(s) found no ground and no height to borrow — they sit at y=0 and riders there will not acquire the route.");
            return network;
        }

        // Why the race line is cut up: AIPathNetwork.TryAcquirePath keeps a rider on
        // its current route for as long as it is inside that route's volume, and
        // only at the route's END does it take one of the route's m_connections
        // (picked once, weighted, by ChooseConnection). One whole-course race line
        // is inside-everywhere, so a rider that starts on it never leaves it and
        // the branches go unraced. So: cut the race line wherever a fragment forks
        // off or merges back, and link piece → next piece, piece → each fragment
        // forking there, fragment → the piece at its merge point. The connection's
        // own bridge (TryProjectConnection) covers the gap between a piece's end and
        // a fragment's first point. Replaces the race line in `routes` with its
        // pieces, may reverse fragments drawn uphill, and returns index pairs into
        // the rewritten list.
        const float MinRaceLinePiece = 100f;   // 1x units; well past the AI's speed*0.5 look-ahead

        const float FragmentJoinReach = 40f;   // 1x units; fragment end → another fragment's start

        private static List<KeyValuePair<int, int>> SplitAndLink(List<RouteDraft> routes, RouteDraft raceLine, float s)
        {
            var links = new List<KeyValuePair<int, int>>();
            var line = raceLine.Points;
            int n = line.Count;
            if (n < 2) return links;
            var cum = new float[n];
            for (int i = 1; i < n; i++)
            {
                float dx = line[i].x - line[i - 1].x, dz = line[i].z - line[i - 1].z;
                cum[i] = cum[i - 1] + Mathf.Sqrt(dx * dx + dz * dz);
            }
            float reach = SpineHalfWidth * s;
            var branches = new List<RouteDraft>();
            foreach (var d in routes) if (d != raceLine) branches.Add(d);
            var fork = new int[branches.Count];   // race-line index, or -1 = not on the line
            var merge = new int[branches.Count];
            int reversed = 0, rails = 0;
            for (int b = 0; b < branches.Count; b++)
            {
                var d = branches[b];
                int i0 = NearestOnLine(line, d.Points[0], out float d0);
                int i1 = NearestOnLine(line, d.Points[d.Points.Count - 1], out float d1);
                if (!string.IsNullOrEmpty(d.RailName))
                {
                    // A rail approach ends at the rail, not back on the line: no merge
                    // (a merge index would also add a cut and shift every other
                    // fragment's piece), and never reversed — it points at the rail's
                    // first segment, which is where TryProjectConnection aims.
                    fork[b] = d0 <= reach ? i0 : -1;
                    merge[b] = -1;
                    rails++;
                    continue;
                }
                if (i1 < i0)
                {
                    // Drawn against the race: the AI would ride it uphill.
                    d.Points.Reverse(); d.Windups.Reverse();
                    int ti = i0; i0 = i1; i1 = ti;
                    float td = d0; d0 = d1; d1 = td;
                    reversed++;
                }
                fork[b] = d0 <= reach ? i0 : -1;
                merge[b] = d1 <= reach ? i1 : -1;
            }

            // Cut points, thinned so no piece is shorter than MinRaceLinePiece.
            var wanted = new SortedSet<int>();
            for (int b = 0; b < branches.Count; b++)
            {
                if (fork[b] > 0) wanted.Add(fork[b]);
                if (merge[b] >= 0 && merge[b] < n - 1) wanted.Add(merge[b]);
            }
            float minPiece = MinRaceLinePiece * s;
            var bounds = new List<int> { 0 };
            foreach (int c in wanted)
                if (cum[c] - cum[bounds[bounds.Count - 1]] >= minPiece && cum[n - 1] - cum[c] >= minPiece)
                    bounds.Add(c);
            bounds.Add(n - 1);
            int pieces = bounds.Count - 1;
            routes.Clear();
            for (int k = 0; k < pieces; k++)
            {
                var piece = new RouteDraft { Name = "AIPath3D (race line " + k.ToString(CultureInfo.InvariantCulture) + ")", Spine = true };
                for (int i = bounds[k]; i <= bounds[k + 1]; i++)
                {
                    piece.Points.Add(line[i]);
                    piece.Windups.Add(raceLine.Windups[i]);
                }
                routes.Add(piece);
                if (k > 0) links.Add(new KeyValuePair<int, int>(k - 1, k));
            }
            int forks = 0, merges = 0, joins = 0, offLine = 0;
            for (int b = 0; b < branches.Count; b++)
            {
                int ri = pieces + b;
                routes.Add(branches[b]);
                if (fork[b] >= 0)
                {
                    int k = SnapToBound(bounds, cum, fork[b]);
                    // k == 0 is the start gate: riders pick among the start volumes by
                    // TryAcquirePath's scan, so nothing needs to hand off to it.
                    if (k > 0) { links.Add(new KeyValuePair<int, int>(k - 1, ri)); forks++; }
                }
                if (!string.IsNullOrEmpty(branches[b].RailName))
                {
                    // Ends in its Rail connection (BuildAIPathNetwork), nothing else.
                }
                else if (merge[b] >= 0)
                {
                    int k = SnapToBound(bounds, cum, merge[b]);
                    if (k < pieces) { links.Add(new KeyValuePair<int, int>(ri, k)); merges++; }
                }
                else
                {
                    var end = branches[b].Points[branches[b].Points.Count - 1];
                    for (int o = 0; o < branches.Count; o++)
                    {
                        if (o == b) continue;
                        var st = branches[o].Points[0];
                        float dx = st.x - end.x, dz = st.z - end.z;
                        if (dx * dx + dz * dz <= FragmentJoinReach * s * FragmentJoinReach * s)
                        { links.Add(new KeyValuePair<int, int>(ri, pieces + o)); joins++; }
                    }
                }
                if (fork[b] < 0 && merge[b] < 0 && string.IsNullOrEmpty(branches[b].RailName)) offLine++;
            }
            Log.LogInfo($"[AIPaths] race line cut into {pieces} piece(s); {forks} fork link(s), {merges} merge link(s), "
                + $"{joins} fragment→fragment link(s), {rails} rail approach(es); {reversed} fragment(s) reversed to run downhill, {offLine} touch the race line at neither end");
            return links;
        }

        private static int NearestOnLine(List<Vector3> line, Vector3 p, out float dist)
        {
            int best = 0; float b2 = float.MaxValue;
            for (int i = 0; i < line.Count; i++)
            {
                float dx = line[i].x - p.x, dz = line[i].z - p.z, d2 = dx * dx + dz * dz;
                if (d2 < b2) { b2 = d2; best = i; }
            }
            dist = Mathf.Sqrt(b2);
            return best;
        }

        // Index into `bounds` of the cut nearest race-line index i, by distance along the line.
        private static int SnapToBound(List<int> bounds, float[] cum, int i)
        {
            int best = 0;
            for (int k = 1; k < bounds.Count; k++)
                if (Mathf.Abs(cum[bounds[k]] - cum[i]) < Mathf.Abs(cum[bounds[best]] - cum[i])) best = k;
            return best;
        }

        // Height for a 2D route point. Seed from the nearest race-line point (the
        // race line is 3D and follows the same run) or the previous point, then
        // cast down from above the seed so a branch in a tunnel lands on the
        // tunnel floor rather than the mountain above it.
        private static float GroundUnderRoute(Vector3 p, RouteDraft raceLine, float prevY, float s,
            ref int grounded, ref int seeded, ref int blind)
        {
            float seed = float.NaN;
            if (raceLine != null)
            {
                float best = float.MaxValue;
                foreach (var r in raceLine.Points)
                {
                    float dx = r.x - p.x, dz = r.z - p.z, d2 = dx * dx + dz * dz;
                    if (d2 < best) { best = d2; seed = r.y; }
                }
            }
            if (float.IsNaN(seed)) seed = prevY;
            Vector3 from;
            float reach;
            if (float.IsNaN(seed)) { from = new Vector3(p.x, 100000f, p.z); reach = 200000f; }
            else { from = new Vector3(p.x, seed + 50f * s, p.z); reach = 400f * s; }
            if (Physics.Raycast(from, Vector3.down, out var hit, reach, SpawnGroundMask, QueryTriggerInteraction.Ignore))
            {
                grounded++;
                return hit.point.y;
            }
            if (!float.IsNaN(seed)) { seeded++; return seed; }
            blind++;
            return 0f;
        }

        // The race line's List<Vector3> DOES deserialize (and is 3D), so it is
        // always available as one complete route to the finish.
        private static RouteDraft RaceLineRoute()
        {
            var raceLine = FindAnyObjectByType<MakerRaceLine>();
            if (raceLine == null || raceLine.m_points == null || raceLine.m_points.Count < 2)
                return null;
            var d = new RouteDraft { Name = "AIPath3D (race line)", Spine = true };
            foreach (var v in raceLine.m_points)
            {
                d.Points.Add(v);
                d.Windups.Add(false);
            }
            Log.LogInfo($"[AIPaths] race line gives 1 complete path ({d.Points.Count} points)");
            return d;
        }

        static void BuildAIPaths(BuildContext ctx)
        {
            var levelManagerMaker = ctx.Maker;
            var levelManager = ctx.LevelManager;
            // World-space objects hang off LevelData, never levelManager: the game's
            // LevelManager root is a Screen Space - Overlay Canvas, which Unity
            // re-lays-out on any window resize/fullscreen toggle, dragging every
            // child with it (respawns landed 1.35x-scaled about z=0, under the course).
            GameObject AIParent = new GameObject("AI Paths Parent");
            AIParent.transform.parent = levelManagerMaker.transform;

            // MakerAIPath.m_points is a List of a user-defined [Serializable]
            // nested class, and Unity fails to deserialize those for
            // runtime-loaded (BepInEx) assemblies — on custom maps every list
            // comes back empty (engine limitation; lists of engine value types
            // like the race line's List<Vector3> are fine). The maker copy below
            // still wins whenever data DID arrive (future fixed bundles);
            // otherwise the routes are rebuilt from a plain-text sidecar next to
            // the .asset, or, failing that, from the race line.
            var routes = new List<RouteDraft>();
            var MakerAIPaths = FindObjectsByType(typeof(MakerAIPath), FindObjectsSortMode.None) as MakerAIPath[];
            for (int i = 0; i < MakerAIPaths.Length; i++)
            {
                if (MakerAIPaths[i].m_points == null || MakerAIPaths[i].m_points.Count < 2)
                    continue;
                var d = new RouteDraft { Name = "AIPath3D (maker " + routes.Count.ToString(CultureInfo.InvariantCulture) + ")" };
                foreach (var mp in MakerAIPaths[i].m_points)
                {
                    // Maker points are 2D (world XZ), like the old AIPath's.
                    d.Points.Add(new Vector3(mp.position.x, float.NaN, mp.position.y));
                    d.Windups.Add(mp.windup);
                }
                routes.Add(d);
            }

            var raceLineDraft = RaceLineRoute();
            if (routes.Count > 0)
            {
                Log.LogInfo($"[AIPaths] copied {routes.Count} maker path(s) from the bundle (sidecar ignored)");
                LoadClock.Mark("AIPaths");
            }
            else
            {
                // Build BOTH sources into the same pool: SSX branch fragments to race
                // on, and the race line as the one route guaranteed to reach the
                // finish. AIPathNetwork.TryAcquirePath keeps a rider on its current
                // route while inside that route's volume and, once it leaves (a
                // fragment end), re-picks the best-scoring volume it is inside — so
                // the race line is the backstop a stranded rider falls back onto.
                // Toggle MultiPathAI off for race-line-only racing without a rebuild.
                int built = raceLineDraft == null ? 0 : 1;
                if (raceLineDraft != null) routes.Add(raceLineDraft);
                int branches = 0;
                if (multiPathAI.Value || built == 0)
                {
                    var side = SidecarRoutes();
                    branches = side.Count;
                    routes.AddRange(side);
                }
                if (built + branches == 0)
                    Log.LogWarning("[AIPaths] no AI path data (maker points empty, no usable race line, no sidecar); AI will hold the start gate but cannot race");
                else
                    Log.LogInfo($"[AIPaths] AI pool: {built} race-line path + {branches} branch path(s) = {built + branches} total"
                        + (multiPathAI.Value ? "" : " (MultiPathAI off)"));
                    LoadClock.Mark("AIPaths");
            }
            var network = BuildAIPathNetwork(AIParent, routes, raceLineDraft);
            LoadClock.Mark("BuildAIPathNetwork");
            SetGameField(fPathNetwork, "LevelManager.pathNetwork", levelManager, network);
        }

        static void BuildRaceLine(BuildContext ctx)
        {
            var levelManager = ctx.LevelManager;
            // ⚠️ A map with no MakerRaceLine is legal — this lookup can and does
            // return null, and dereferencing it threw an NRE straight out of a Unity
            // Awake postfix. That lands in Player.log and NOWHERE in the BepInEx log
            // (root CLAUDE.md, HOOK_NOTES §23), and it aborted the REST of
            // LoadLevelManager: no respawn markers, no glass strip, no wind volumes,
            // no skydome, no destructibles — a half-imported map with a clean log.
            // BuildAIPathFromRaceLine already null-checks the same lookup; this is
            // the other half of that guard.
            var TempMakerRaceLine = FindAnyObjectByType<MakerRaceLine>();
            RaceLine TempRaceLine = null;
            if (TempMakerRaceLine == null || TempMakerRaceLine.m_points == null
                || TempMakerRaceLine.m_points.Count == 0)
            {
                Log.LogWarning("[RaceLine] no usable MakerRaceLine in this map ("
                    + (TempMakerRaceLine == null
                        ? "no MakerRaceLine component anywhere in the scene"
                        : "MakerRaceLine present but its m_points list is empty")
                    + ") — LevelManager.raceLine stays NULL. Rank/position, race-line respawn "
                    + "markers and the AI mod's race terminator are all off for this course; the "
                    + "rest of the level build continues.");
            }
            else
            {
                TempRaceLine = TempMakerRaceLine.gameObject.AddComponent<RaceLine>();

                TempRaceLine.m_points = new List<RaceLine.Point>();

                for (int i = 0;i < TempMakerRaceLine.m_points.Count;i++)
                {
                    var RaceLinePoint = new RaceLine.Point();

                    RaceLinePoint.position = TempMakerRaceLine.m_points[i];

                    TempRaceLine.m_points.Add(RaceLinePoint);
                }

                TempRaceLine.CalculateSegments();
                LoadClock.Mark("RaceLine.CalculateSegments");

                SetGameField(fRaceLine, "LevelManager.raceLine", levelManager, TempRaceLine);
            }
            ctx.RaceLine = TempRaceLine;
        }
